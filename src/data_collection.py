"""Download daily Colombo weather from the Open-Meteo Historical Weather API.

The API serves reanalysis products, which combine observations with numerical
weather models; these are historical weather estimates, not simulated rows
generated by this project. See https://open-meteo.com/en/docs/historical-weather-api.
"""

from __future__ import annotations

from datetime import date, datetime, timedelta
from pathlib import Path
from zoneinfo import ZoneInfo

import pandas as pd
import requests
from requests.adapters import HTTPAdapter
from urllib3.util.retry import Retry

API_URL = "https://archive-api.open-meteo.com/v1/archive"
LATITUDE = 6.9271
LONGITUDE = 79.8612
TIMEZONE = "Asia/Colombo"
START_DATE = date(2016, 1, 1)
OUTPUT_PATH = Path(__file__).resolve().parents[1] / "data" / "raw" / "sri_lanka_weather.csv"
DAILY_VARIABLES = [
    "temperature_2m_max",
    "temperature_2m_min",
    "temperature_2m_mean",
    "precipitation_sum",
    "wind_speed_10m_max",
]
HOURLY_VARIABLES = ["relative_humidity_2m"]


def _session() -> requests.Session:
    """Create an HTTP session with retries for transient API failures."""
    session = requests.Session()
    retry = Retry(
        total=4,
        connect=4,
        read=4,
        backoff_factor=1,
        status_forcelist=(429, 500, 502, 503, 504),
        allowed_methods=("GET",),
    )
    session.mount("https://", HTTPAdapter(max_retries=retry))
    return session


def fetch_weather() -> pd.DataFrame:
    """Fetch daily and hourly humidity data and validate API response fields."""
    # Archive data is updated with a delay; asking through today lets the API
    # return its latest available complete daily record.
    end_date = datetime.now(ZoneInfo(TIMEZONE)).date()
    params = {
        "latitude": LATITUDE,
        "longitude": LONGITUDE,
        "start_date": START_DATE.isoformat(),
        "end_date": end_date.isoformat(),
        "daily": ",".join(DAILY_VARIABLES),
        "hourly": ",".join(HOURLY_VARIABLES),
        "timezone": TIMEZONE,
    }
    try:
        response = _session().get(API_URL, params=params, timeout=(15, 120))
        response.raise_for_status()
        payload = response.json()
    except (requests.RequestException, ValueError) as exc:
        raise RuntimeError(f"Open-Meteo request failed: {exc}") from exc

    if not isinstance(payload, dict) or payload.get("error"):
        raise RuntimeError(f"Invalid Open-Meteo response: {payload.get('reason', payload)}")
    daily = payload.get("daily")
    if not isinstance(daily, dict) or "time" not in daily:
        raise RuntimeError("API response is missing daily data or its time field.")
    missing_fields = [name for name in DAILY_VARIABLES if name not in daily]
    if missing_fields:
        raise RuntimeError(f"API response is missing requested daily fields: {missing_fields}")
    lengths = {len(daily[name]) for name in ["time", *DAILY_VARIABLES]}
    if len(lengths) != 1 or not daily["time"]:
        raise RuntimeError("Daily API arrays are empty or have inconsistent lengths.")

    result = pd.DataFrame({"date": pd.to_datetime(daily["time"], errors="raise")})
    for name in DAILY_VARIABLES:
        result[name] = pd.to_numeric(daily[name], errors="coerce")

    # Humidity is optional: aggregate the returned hourly values by Colombo
    # calendar date. Missing hourly values remain missing (no imputation).
    hourly = payload.get("hourly")
    if isinstance(hourly, dict) and "time" in hourly and "relative_humidity_2m" in hourly:
        if len(hourly["time"]) != len(hourly["relative_humidity_2m"]):
            raise RuntimeError("Hourly humidity API arrays have inconsistent lengths.")
        humidity = pd.DataFrame(
            {
                "date": pd.to_datetime(hourly["time"], errors="raise").normalize(),
                "relative_humidity_2m": pd.to_numeric(
                    hourly["relative_humidity_2m"], errors="coerce"
                ),
            }
        )
        humidity_daily = humidity.groupby("date", as_index=False)["relative_humidity_2m"].mean()
        result = result.merge(humidity_daily, on="date", how="left", validate="one_to_one")
    else:
        result["relative_humidity_2m"] = pd.NA

    result = result.sort_values("date").drop_duplicates("date", keep="first").reset_index(drop=True)
    if result["date"].min().date() != START_DATE:
        raise RuntimeError(f"Unexpected first date in API response: {result['date'].min().date()}")
    return result


def main() -> None:
    """Download observations, persist the raw CSV, and report coverage."""
    try:
        weather = fetch_weather()
    except Exception as exc:
        raise SystemExit(f"Weather collection stopped: {exc}") from exc
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    weather.to_csv(OUTPUT_PATH, index=False, date_format="%Y-%m-%d")
    print(f"Saved {len(weather):,} daily records to {OUTPUT_PATH}")
    print(f"Date range: {weather['date'].min().date()} to {weather['date'].max().date()}")
    print("Missing values by column:")
    print(weather.isna().sum().to_string())


if __name__ == "__main__":
    main()
